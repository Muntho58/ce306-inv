CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories (id),
    current_stock INTEGER NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
    predicted_stock INTEGER NOT NULL DEFAULT 0 CHECK (predicted_stock >= 0),
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    status TEXT NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    total_sales BIGINT NOT NULL DEFAULT 0 CHECK (total_sales >= 0),
    image_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS orders (
    id TEXT PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers (id),
    order_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    payment_status TEXT NOT NULL
        CHECK (payment_status IN ('Paid', 'Pending', 'Unpaid')),
    status TEXT NOT NULL DEFAULT 'New Order'
        CHECK (status IN ('New Order', 'Accepted', 'Ready to ship', 'Delivered', 'Returned')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS order_items (
    order_id TEXT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products (id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE INDEX IF NOT EXISTS products_category_id_idx ON products (category_id);
CREATE INDEX IF NOT EXISTS orders_customer_id_idx ON orders (customer_id);
CREATE INDEX IF NOT EXISTS orders_order_date_idx ON orders (order_date);
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status);

